-- Intended Supabase/PostgreSQL schema baseline. Apply through controlled migration tooling.
create table if not exists categories (
  id bigint generated by default as identity primary key,
  slug text not null unique,
  name text not null unique,
  description text,
  archived boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists products (
  id bigint generated by default as identity primary key,
  sku text not null unique,
  slug text not null unique,
  name text not null,
  description text not null,
  price numeric(10,2),
  image_url text,
  published boolean not null default false,
  featured boolean not null default false,
  available_for_order boolean not null default false,
  category_id bigint references categories(id),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint published_product_has_price check (not published or price is not null)
);

create table if not exists product_variants (
  id bigint generated by default as identity primary key,
  product_id bigint not null references products(id) on delete cascade,
  sku text not null unique,
  name text not null,
  price numeric(10,2) not null check (price >= 0),
  available_for_order boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists role_assignments (
  id bigint generated by default as identity primary key,
  user_id uuid not null unique references auth.users(id),
  role text not null check (role in ('customer','catalog_manager','admin')) default 'customer',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists orders (
  id bigint generated by default as identity primary key,
  reference text not null unique,
  customer_id uuid references auth.users(id),
  customer_name text not null,
  customer_phone text not null,
  status text not null check (status in ('pending','awaiting_confirmation','confirmed','processing','shipped','delivered','cancelled')),
  total numeric(10,2) not null check (total >= 0),
  idempotency_key text not null unique,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists order_items (
  id bigint generated by default as identity primary key,
  order_id bigint not null references orders(id) on delete cascade,
  product_id bigint not null references products(id),
  variant_id bigint references product_variants(id),
  product_name text not null,
  variant_name text,
  quantity integer not null check (quantity > 0),
  unit_price numeric(10,2) not null check (unit_price >= 0)
);

alter table categories enable row level security;
alter table products enable row level security;
alter table product_variants enable row level security;
alter table role_assignments enable row level security;
alter table orders enable row level security;
alter table order_items enable row level security;

drop policy if exists "public reads published products" on products;
create policy "public reads published products" on products for select using (published = true);

drop policy if exists "public reads variants for published products" on product_variants;
create policy "public reads variants for published products" on product_variants for select using (
  exists (select 1 from products where products.id = product_variants.product_id and products.published = true)
);

drop policy if exists "public reads active categories" on categories;
create policy "public reads active categories" on categories for select using (archived = false);

drop policy if exists "customers read own orders" on orders;
create policy "customers read own orders" on orders for select using (customer_id = auth.uid());

drop policy if exists "users read their own role only" on role_assignments;
create policy "users read their own role only" on role_assignments for select using (user_id = auth.uid());

drop policy if exists "customers read own order items" on order_items;
create policy "customers read own order items" on order_items for select using (
  exists (select 1 from orders where orders.id = order_items.order_id and orders.customer_id = auth.uid())
);

